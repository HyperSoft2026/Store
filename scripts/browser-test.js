'use strict';
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const net = require('node:net');
const { Pool } = require('pg');
function freePort(){return new Promise((resolve,reject)=>{const s=net.createServer();s.once('error',reject);s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(e=>e?reject(e):resolve(p));});});}
(async()=>{
 const dbUrl=process.env.BROWSER_DATABASE_URL;
 if(!dbUrl){console.log('Browser tests skipped: BROWSER_DATABASE_URL not configured.');return;}
 const { chromium }=require('playwright');
 const port=await freePort(), adminLink='/browser-test-admin-route';
 const child=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:String(port),NODE_ENV:'test',POSTGRESQL_ADDON_URI:dbUrl,ADMIN_USERNAME:'store-browser-user',ADMIN_PASSWORD:'browser-test-password-only',ADMIN_LINK:adminLink,PGSSLMODE:'disable'},stdio:['ignore','pipe','pipe']});
 let logs='';child.stdout.on('data',c=>logs+=c.toString());child.stderr.on('data',c=>logs+=c.toString());
 const base='http://127.0.0.1:'+port;let browser;
 const pool=new Pool({connectionString:dbUrl,ssl:false});
 try{
  let ready=false;const deadline=Date.now()+15000;
  while(Date.now()<deadline){if(child.exitCode!==null)throw Error('Browser-test server exited: '+logs);try{const r=await fetch(base+'/api/health');const d=await r.json();if(r.status===200&&d.database==='connected'){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,150));}
  assert.ok(ready,'browser-test server should become healthy: '+logs);
  browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const pageErrors=[];page.on('pageerror',e=>pageErrors.push(e.message));
  await page.goto(base+adminLink,{waitUntil:'networkidle'});
  await page.locator('#username').fill('store-browser-user');
  await page.locator('#password').fill('browser-test-password-only');
  await page.locator('#login-submit').click();
  await page.locator('#admin-screen').waitFor({state:'visible',timeout:10000});
  await page.locator('#new-post').click();
  await page.locator('#post-title').fill('Browser QA Post');
  await page.locator('#post-slug').fill('browser-qa-post');
  await page.locator('#post-category').fill('Automated QA');
  await page.locator('#post-excerpt').fill('Published from a real browser test.');
  await page.locator('#post-content').fill('Browser integration content.');
  await page.locator('#post-status').selectOption('published');
  await page.locator('#save-post').click();
  await page.locator('#editor-modal').waitFor({state:'hidden',timeout:10000});
  await page.locator('[data-admin-view="products"]').click();
  await page.locator('#new-product').click();
  await page.locator('#product-name').fill('Browser QA Product');
  await page.locator('#product-slug').fill('browser-qa-product');
  await page.locator('#product-developer').fill('Automated QA');
  await page.locator('#product-short').fill('Published from Chromium.');
  await page.locator('#product-description').fill('Product details for browser acceptance tests.');
  await page.locator('#product-download').fill('https://example.test/browser-qa.apk');
  await page.locator('#product-version').fill('1.0');
  await page.locator('#product-rating').fill('4.2');
  await page.locator('#product-published').check();
  await page.locator('#product-save').click();
  await page.getByText('تم حفظ المنتج.',{exact:true}).waitFor({state:'visible',timeout:10000});
  await page.goto(base+'/',{waitUntil:'networkidle'});
  await page.locator('#menu-toggle').click();
  assert.ok(await page.locator('#sidebar').evaluate(el=>el.classList.contains('open')),'hamburger should open the navigation drawer');
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'),'true','hamburger should expose expanded state');
  await page.keyboard.press('Escape');
  assert.ok(!(await page.locator('#sidebar').evaluate(el=>el.classList.contains('open'))),'Escape should close the navigation drawer');
  await page.getByText('Browser QA Post',{exact:true}).waitFor({state:'visible',timeout:10000});
  await page.getByText('Browser QA Product',{exact:true}).waitFor({state:'visible',timeout:10000});
  await page.locator('[data-product="browser-qa-product"]').first().click();
  await page.locator('#product-dialog').waitFor({state:'visible',timeout:10000});
  await page.locator('#download-product').waitFor({state:'visible',timeout:5000});
  await page.locator('.dialog-close').click();
  await page.locator('#search-input').fill('Browser QA Product');
  await page.locator('#search-form').locator('button[type="submit"]').click();
  const qaCard=page.locator('.product-card').filter({hasText:'Browser QA Product'});
  await qaCard.waitFor({state:'visible',timeout:10000});
  assert.equal((await qaCard.locator('.rating-value').innerText()).trim(),'4.2','product card should display its database rating');
  assert.equal(await qaCard.locator('.rating-star').count(),5,'product card should render five stars');
  assert.equal(await qaCard.locator('.product-title a').getAttribute('href'),'/product/browser-qa-product','product title should link to details');
  assert.equal(await qaCard.locator('.product-link').innerText().then(s=>s.trim().replace(/\s+/g,' ')),'تحميل ←','product card action should display تحميل');
  await qaCard.locator('.product-link').click();
  await page.locator('#product-dialog').waitFor({state:'visible',timeout:10000});
  assert.equal(new URL(page.url()).pathname,'/product/browser-qa-product','تحميل should navigate to product details');
  await page.locator('#product-dialog .dialog-close').click();
  await page.waitForURL('**/',{timeout:5000});
  const mobileOverflow=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
  assert.ok(mobileOverflow.width<=mobileOverflow.viewport+1,'storefront should not overflow on mobile: '+JSON.stringify(mobileOverflow));
  await page.setViewportSize({width:1280,height:900});
  await page.reload({waitUntil:'networkidle'});
  const desktopOverflow=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:document.documentElement.clientWidth}));
  assert.ok(desktopOverflow.width<=desktopOverflow.viewport+1,'storefront should not overflow on desktop: '+JSON.stringify(desktopOverflow));
  assert.deepEqual(pageErrors,[],'browser pages should not raise uncaught JavaScript errors');
  console.log('Browser tests passed: admin login, publish post, public rendering, mobile viewport and no uncaught page errors.');
 }finally{
  if(browser)await browser.close().catch(()=>{});
  await pool.query("DELETE FROM store_posts WHERE slug='browser-qa-post'").catch(()=>{});
  await pool.query("DELETE FROM store_products WHERE slug='browser-qa-product'").catch(()=>{});
  await pool.end().catch(()=>{});
  child.kill('SIGTERM');
  await new Promise(resolve=>{if(child.exitCode!==null)return resolve();const t=setTimeout(resolve,1500);child.once('exit',()=>{clearTimeout(t);resolve();});});
 }
})().catch(e=>{console.error(e);process.exitCode=1;});
