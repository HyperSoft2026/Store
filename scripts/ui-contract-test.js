'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const admin = fs.readFileSync(require.resolve('../admin/index.html'), 'utf8');
const storefront = fs.readFileSync(require.resolve('../public/index.html'), 'utf8');
const app = fs.readFileSync(require.resolve('../public/app.js'), 'utf8');
const styles = fs.readFileSync(require.resolve('../public/styles.css'), 'utf8');
const adminStyles = fs.readFileSync(require.resolve('../public/admin-assets.css'), 'utf8');
const server = fs.readFileSync(require.resolve('../server.js'), 'utf8');
assert.match(admin, /name="robots" content="noindex,nofollow,noarchive"/, 'admin page should discourage indexing');
assert.ok(admin.indexOf('/admin-utils.js?v=1.0.0') < admin.indexOf('/admin-assets.js?v=1.0.0'), 'slug utility must load before admin controller');
assert.match(admin, /id="login-form"/, 'admin login form should exist');
assert.match(admin, /id="post-form"/, 'post editor form should exist');
assert.match(admin, /id="product-form"/, 'product editor form should exist');
assert.match(admin, /id="category-form"/, 'category editor form should exist');
assert.ok(storefront.includes('/styles.css?v=1.0.0'), 'storefront CSS cache key should match release');
assert.ok(storefront.includes('/app.js?v=1.0.0'), 'storefront JS cache key should match release');
assert.ok(app.includes('/posts.css?v=1.0.0'), 'posts CSS cache key should match release');
assert.match(app, /const requestId = \+\+state\.routeRequest/, 'each route load should have a unique request id');
assert.match(app, /if \(requestId !== state\.routeRequest\) return/, 'stale route responses should be ignored');
assert.ok(server.includes('hasDownload: Boolean(row.download_url)'), 'public API should expose availability flag, not URL');
assert.ok(!server.includes('downloadUrl: row.download_url'), 'public API must not expose the raw download URL');
assert.match(server, /store_admin_sessions/, 'admin sessions should be database-backed');
assert.match(server, /store_admin_attempts/, 'login throttling should be database-backed');
assert.match(storefront, /aria-controls="sidebar"/, 'main menu button should control the navigation drawer');
assert.ok(app.includes('التفاصيل <span aria-hidden="true">←</span>'), 'product cards should link to product details');
assert.ok(!storefront.includes('لوحة التحكم') && !storefront.includes('لوحة الإدارة'), 'admin panel must not be linked from the public storefront');
assert.match(server, /app\.get\(ADMIN_PATH/, 'admin page must only be mounted at the configured private path');

assert.equal((storefront.match(/id="menu-toggle"/g) || []).length, 1, 'there must be exactly one hamburger control');
assert.match(storefront, /aria-controls="sidebar"/, 'main menu button should control the navigation drawer');
assert.match(styles, /\[hidden\]\s*\{\s*display:\s*none\s*!important;\s*\}/, 'hidden overlays must remain hidden until opened');
assert.match(styles, /--green:\s*#16834A/, 'storefront primary theme must be green');
assert.match(adminStyles, /--green:\s*#16834A/, 'admin primary theme must be green');
assert.ok(!adminStyles.includes('#dce9ff') && !adminStyles.includes('#e9f1ff'), 'admin stylesheet should not retain the old blue palette');
assert.match(app, /history\.pushState\(\{\}, '', url\.pathname \+ url\.search\)/, 'navigation should update shareable browser history');
assert.match(app, /path\.startsWith\('\/product\/'\)/, 'direct product detail routes should be supported');
assert.match(app, /path === '\/games'/, 'game catalog route should be supported');
assert.match(app, /path === '\/apps'/, 'app catalog route should be supported');
assert.match(app, /path === '\/search'/, 'shareable search route should be supported');
assert.match(app, /categorySlug/, 'category routes should use product category data');
assert.match(app, /showModal\(\)/, 'screenshots should open in an accessible modal');
assert.ok(!storefront.includes('لوحة التحكم') && !storefront.includes('لوحة الإدارة') && !storefront.includes('/admin/index.html'), 'admin panel must not be linked from the public storefront');
assert.match(server, /app\.get\(ADMIN_PATH/, 'admin page must only be mounted at the configured private path');
assert.match(server, /ADD COLUMN IF NOT EXISTS product_type TEXT/, 'existing databases should receive the product type column');
assert.match(server, /ADD COLUMN IF NOT EXISTS status TEXT/, 'existing databases should receive the product status column');
assert.match(server, /ADD COLUMN IF NOT EXISTS screenshots TEXT\[\]/, 'existing databases should receive screenshot metadata');
assert.match(server, /rating: row\.rating == null \? null : Number\(row\.rating\)/, 'API should return the actual nullable rating from PostgreSQL');
assert.match(server, /p\.is_published = TRUE.*p\.status = 'published'/, 'public listing should require both published flags');
assert.match(server, /downloads > 0/, 'popular catalog should require recorded downloads');
assert.match(app, /class="product-rating"/, 'product cards should show stored ratings when present');
assert.match(app, /class="rating-star"/, 'product cards should render a rating marker');
assert.match(app, /href="\$\{slugPath\('\/product', item\.slug\)\}"/, 'product cards should link to detail routes');
assert.match(styles, /scroll-snap-type: x mandatory/, 'product screenshot gallery should support horizontal scrolling');
assert.match(admin, /id="product-rating"/, 'admin should provide an optional product rating field');
assert.match(admin, /id="product-preview"/, 'admin should offer a pre-publish product preview');
assert.match(admin, /id="product-type-filter"/, 'admin should offer product type filters');
assert.match(admin, /id="product-status-filter"/, 'admin should offer product status filters');
console.log('UI contract tests passed: private admin route, catalog routes, public status guard, previews and responsive detail views.');
