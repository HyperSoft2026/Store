'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const admin = fs.readFileSync(require.resolve('../admin/index.html'), 'utf8');
const storefront = fs.readFileSync(require.resolve('../public/index.html'), 'utf8');
const app = fs.readFileSync(require.resolve('../public/app.js'), 'utf8');
const styles = fs.readFileSync(require.resolve('../public/styles.css'), 'utf8');
const adminStyles = fs.readFileSync(require.resolve('../public/admin-assets.css'), 'utf8');
const server = fs.readFileSync(require.resolve('../server.js'), 'utf8');
assert.match(admin, /name="robots" content="noindex,nofollow,noarchive"/, 'admin page should discourage indexing');
assert.ok(admin.indexOf('/admin-utils.js?v=0.0.4') < admin.indexOf('/admin-assets.js?v=0.0.4'), 'slug utility must load before admin controller');
assert.match(admin, /id="login-form"/, 'admin login form should exist');
assert.match(admin, /id="post-form"/, 'post editor form should exist');
assert.match(admin, /id="product-form"/, 'product editor form should exist');
assert.match(admin, /id="category-form"/, 'category editor form should exist');
assert.ok(storefront.includes('/styles.css?v=0.0.4'), 'storefront CSS cache key should match release');
assert.ok(storefront.includes('/app.js?v=0.0.4'), 'storefront JS cache key should match release');
assert.ok(app.includes('/posts.css?v=0.0.4'), 'posts CSS cache key should match release');
assert.match(app, /downloadButton.hidden = !item.hasDownload/, 'unavailable download button should be hidden');
assert.match(app, /const requestId = \+\+state\.requestId/, 'each product load should have a unique request id');
assert.match(app, /if \(requestId !== state\.requestId\) return/, 'stale product responses should be ignored');
assert.ok(server.includes('hasDownload: Boolean(row.download_url)'), 'public API should expose availability flag, not URL');
assert.ok(!server.includes('downloadUrl: row.download_url'), 'public API must not expose the raw download URL');
assert.match(server, /store_admin_sessions/, 'admin sessions should be database-backed');
assert.match(server, /store_admin_attempts/, 'login throttling should be database-backed');
assert.match(storefront, /aria-controls="sidebar"/, 'main menu button should control the navigation drawer');
assert.ok(app.includes('تحميل <span aria-hidden="true">←</span>'), 'product card action should say تحميل');
assert.ok(!storefront.includes('لوحة التحكم') && !storefront.includes('لوحة الإدارة'), 'admin panel must not be linked from the public storefront');
assert.match(server, /app\.get\(ADMIN_PATH/, 'admin page must only be mounted at the configured private path');

assert.equal((storefront.match(/id="menu-toggle"/g) || []).length, 1, 'there must be exactly one hamburger control');
assert.match(storefront, /aria-controls="sidebar"/, 'main menu button should control the navigation drawer');
assert.match(styles, /\[hidden\]\s*\{display:none!important\}/, 'hidden overlay must remain hidden until opened');
assert.match(styles, /--primary:#16834a/, 'storefront primary theme must be green');
assert.match(adminStyles, /--blue:#16834a/, 'admin primary theme must be green');
assert.ok(!adminStyles.includes('#dce9ff') && !adminStyles.includes('#e9f1ff'), 'admin stylesheet must not retain the old blue palette');
assert.match(app, /تحميل <span aria-hidden="true">←<\/span>/, 'product card action should say تحميل');
assert.match(app, /history\.pushState\(\{ product: slug \}, '', '\/product\/' \+ encodeURIComponent\(slug\)\)/, 'product action must navigate to its detail URL');
assert.match(app, /showProductDetails\(slug\)/, 'product action must load the detail view');
assert.ok(!storefront.includes('لوحة التحكم') && !storefront.includes('لوحة الإدارة') && !storefront.includes('/admin/index.html'), 'admin panel must not be linked from the public storefront');
assert.match(server, /app\.get\(ADMIN_PATH/, 'admin page must only be mounted at the configured private path');
console.log('UI contract tests passed: private admin route, theme, one accessible menu, detail navigation and download availability.');
